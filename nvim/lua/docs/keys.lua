-- docs/keys.lua — dump this config's keymaps as markdown for docs/keys.md.
-- Run via scripts/keys.sh (headless nvim), not by hand.
--
-- Covers:
--   * every global keymap (the config gives each one a `desc`)
--   * per-buffer keymaps registered on attach (gitsigns in git repos, LSP +
--     completion + telescope LSP pickers in code files) — dumped from a scratch
--     lua buffer after giving a language server a moment to attach
--   * a static list of keymaps that only exist while a specific UI is open
--     (explorer splits, markdown preview)

local M = {}

local MODES = { 'n', 'x', 'v', 'o', 'i', 't' }
local LABEL = {
	n = 'Normal',
	x = 'Visual (charwise)',
	v = 'Visual (linewise)',
	o = 'Operator-pending',
	i = 'Insert',
	t = 'Terminal',
}

local function cell(s)
	return tostring(s or ''):gsub('|', '\\|')
end

-- Leading spaces in a lhs are <Space> (leader); render them so the table is readable.
local function pretty_lhs(lhs)
	local n, s = 0, lhs
	while s:sub(1, 1) == ' ' do
		n = n + 1
		s = s:sub(2)
	end
	return (('<Space>'):rep(n)) .. s
end

-- Noise filters. Kept keys are everything the config (and its plugins) defines
-- with a desc, or a built-in worth knowing. Dropped: nvim 0.12 core defaults
-- (stable, in :help — they exist in every 0.12 install, not "this config"),
-- plugin internals, and dead default entries.
local CORE_LSP_GLOBAL = { grn = 1, gra = 1, grx = 1, grr = 1, gri = 1, grt = 1, gO = 1 }
local function skip(km, section)
	local lhs = km.lhs or ''
	if lhs:match('^<Plug>') then
		return true
	end
	local desc = km.desc
	local rhs = km.rhs
	if not (desc and desc ~= '') and not (rhs and rhs ~= '') then
		return true -- dead default entry (`,`, `;`, `f`, ...)
	end
	if desc and desc:match('^:help') then
		return true -- built-in default mappings (Y, &, <C-U>, ...)
	end
	if desc and desc:match('^:%w+$') then
		return true -- core quickfix/buffer nav defaults (desc is the bare command)
	end
	if desc and desc:match('^vim%.lsp%.') then
		return true -- core LSP defaults rendered as function strings (K, ...)
	end
	if rhs and rhs:match('^<Plug>') then
		return true -- matchit % keys
	end
	if desc == 'autopairs map key' then
		return true
	end
	if section == 'global' and CORE_LSP_GLOBAL[lhs] then
		return true -- config's own versions appear in the on-attach section
	end
	return false
end

local function table_for(kms, section)
	local rows = { '| Key | Action |', '| --- | --- |' }
	local kept = {}
	for _, km in ipairs(kms) do
		if not skip(km, section) then
			table.insert(kept, km)
		end
	end
	table.sort(kept, function(a, b)
		return (a.lhs or ''):lower() < (b.lhs or ''):lower()
	end)
	local seen = {}
	for _, km in ipairs(kept) do
		if not seen[km.lhs] then
			seen[km.lhs] = true
			local what = (km.desc and km.desc ~= '') and km.desc or km.rhs
			table.insert(rows, string.format('| `%s` | %s |', cell(pretty_lhs(km.lhs)), cell(what)))
		end
	end
	return table.concat(rows, '\n')
end

function M.dump()
	local out = {}
	local w = function(line)
		table.insert(out, line)
	end

	-- Per-buffer keymaps only exist on real buffers. Open a scratch lua buffer
	-- and wait briefly so an installed language server can attach.
	vim.cmd('enew')
	vim.bo.filetype = 'lua'
	vim.wait(8000, function()
		return #vim.lsp.get_clients() > 0
	end, 100)

	w('# Keymaps')
	w('')
	w('_Generated by `scripts/keys.sh` from the config itself. Do not edit by hand — change the config, re-run the script._')
	w('')

	w('## Global')
	w('')
	for _, mode in ipairs(MODES) do
		local kms = {}
		for _, km in ipairs(vim.api.nvim_get_keymap(mode)) do
			if km.buffer == 0 then
				table.insert(kms, km)
			end
		end
		if #kms > 0 then
			w('### ' .. LABEL[mode])
			w('')
			w(table_for(kms, 'global'))
			w('')
		end
	end

	w('## On attach (per buffer)')
	w('')
	w('Registered when a buffer is opened: gitsigns (any file in a git repo), LSP, completion and the telescope LSP pickers (code files).')
	w('')
	local buf = vim.api.nvim_get_current_buf()
	local attached = false
	for _, mode in ipairs({ 'n', 'x', 'v', 'o', 'i' }) do
		local kms = vim.api.nvim_buf_get_keymap(buf, mode)
		if #kms > 0 then
			attached = true
			w('### ' .. LABEL[mode])
			w('')
			w(table_for(kms, 'attach'))
			w('')
		end
	end
	if not attached then
		w('_Nothing attached in time (the first run installs LSP servers via mason) — open nvim once normally, then re-run `scripts/keys.sh`._')
		w('')
	end

	w('## Opened in context (static)')
	w('')
	w('These only exist while a specific UI is open, so they are listed here instead of dumped:')
	w('')
	w('| Where | Key | Action |')
	w('| --- | --- | --- |')
	w('| mini.files explorer (`-`) | `<C-v>` / `<C-x>` | open file in a vertical / horizontal split |')
	w('| markdown file | `<Space>mp` | toggle browser preview |')
	w('')

	io.stdout:write(table.concat(out, '\n') .. '\n')
end

return M
